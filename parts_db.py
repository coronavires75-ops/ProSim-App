def get_categories_tree():
    tree = {}
    for item in CATALOG:
        c = item['cat']
        s = item.get('subcat', 'عام')
        if c not in tree:
            tree[c] = []
        if s not in tree[c]:
            tree[c].append(s)
    return tree

CATEGORIES_TREE = get_categories_tree()

def search_catalog(query='', category='الكل', subcategory='الكل', limit=100, offset=0):
    q = query.strip().lower()
    exact, starts, contains = [], [], []
    for item in CATALOG:
        if category != 'الكل' and item['cat'] != category:
            continue
        if subcategory != 'الكل' and item.get('subcat', 'عام') != subcategory:
            continue
        p_low = item['part'].lower()
        n_low = item['name'].lower()
        if not q:
            contains.append(item)
        elif p_low == q:
            exact.append(item)
        elif p_low.startswith(q):
            starts.append(item)
        elif q in p_low or q in n_low:
            contains.append(item)
    merged = exact + starts + contains
    return {'total_matched': len(merged), 'items': merged[offset:offset + limit]}
